#!/usr/bin/env bash
# Install the Hermes cron entrypoint ~/.hermes/scripts/lakehouse_finops.sh.
# Hermes only runs scripts that physically live under ~/.hermes/scripts/ (symlinks out are rejected),
# and cron workers get a minimal PATH, so the wrapper pins the directories of the CLIs found now.
set -euo pipefail

REPO=$(cd "$(dirname "$0")/.." && pwd)
DEST="${HERMES_HOME:-$HOME/.hermes}/scripts/lakehouse_finops.sh"

path=""
for bin in python3 databricks gcloud jq perl; do
  found=$(command -v "$bin") || { echo "missing required CLI: $bin" >&2; exit 1; }
  dir=$(dirname "$found")
  case ":$path:" in *":$dir:"*) ;; *) path="${path:+$path:}$dir" ;; esac
done

# Settings from the Docker deploy are pinned too, since the cron worker's env is not guaranteed.
exports=""
for var in TZ FINOPS_CONFIG FINOPS_DB_PATH DATABRICKS_CONFIG_FILE CLOUDSDK_CONFIG; do
  val=$(printenv "$var") || continue
  exports="${exports}export $var=$(printf '%q' "$val")
"
done

mkdir -p "$(dirname "$DEST")"
cat >"$DEST" <<WRAPPER
#!/usr/bin/env bash
# Generated by $REPO/scripts/install_hermes.sh. Do not edit; rerun the installer instead.
export PATH="$path:/usr/bin:/bin:/usr/sbin:/sbin"
${exports}exec "$REPO/scripts/run_audit.sh" "\$@"
WRAPPER
chmod 755 "$DEST"
echo "installed $DEST"
