"""Feed made-up collector output through the FinOps pipeline into a separate demo DB.

For every weekday 08:00 Bangkok run from 1 Oct 2026 up to now, writes the JSON files the shell
collectors would produce (OUT/runs/<run_id>/compute_*.json, storage_*.json), then evaluates them
with the real rules, trend and DB code, as `python3 -m finops run` does, but with the run's own
clock. Writes OUT/demo.toml (config/auditor.toml with environment "Demo-Lakehouse") for the demo
web dashboard. Never touches the production DB; rerunning rebuilds OUT/demo.db from scratch.

Usage: python3 demo/make_demo.py [OUT]   (default OUT: demo/out)
"""

from __future__ import annotations

import json
import random
import re
import sys
from datetime import datetime, time, timedelta, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from finops import config as config_mod  # noqa: E402
from finops import db, report, rules, trends  # noqa: E402
from finops.__main__ import RunRecord, load_run_dir  # noqa: E402
from finops.config import Config  # noqa: E402

ENVIRONMENT = "Demo-Lakehouse"
FIRST_DAY = datetime(2026, 10, 1)
GB, MB = rules.GB, rules.MB


def ms(dt: datetime) -> int:
    return int(dt.timestamp() * 1000)


def iso(dt: datetime) -> str:
    return dt.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.000Z")


def write_config(out: Path) -> Config:
    """The production config with the demo environment name, so thresholds and rates stay in step."""
    text = (ROOT / "config" / "auditor.toml").read_text()
    text = re.sub(r"(?m)^environment_name = .*$", f'environment_name = "{ENVIRONMENT}"', text)
    text = re.sub(r"(?m)^db_path = .*$", 'db_path = "demo.db"  # demo only; make_demo.py and the demo web pass --db', text)
    path = out / "demo.toml"
    path.write_text("# Generated by demo/make_demo.py from config/auditor.toml; do not edit.\n" + text)
    return config_mod.load(path)


def run_times(cfg: Config, now: datetime) -> list[datetime]:
    """Weekday 08:00 Bangkok runs from FIRST_DAY up to now, with the scheduler's ~1 minute of jitter."""
    rng = random.Random(7)
    out, day = [], FIRST_DAY
    while True:
        t = datetime.combine(day.date(), time(8, 0), cfg.tz) + timedelta(seconds=rng.uniform(20, 90))
        if t > now:
            return out
        if t.weekday() < 5:
            out.append(t.astimezone(timezone.utc))
        day += timedelta(days=1)


# ------------------------------------------------------------- compute (Module A)


def databricks_clusters(i: int, last: bool, t: datetime, rng: random.Random) -> list[dict]:
    def cluster(cid, name, source, autoterm, workers, node, cores, running, start=None, activity=None):
        return {
            "platform": "databricks", "profile": "lakehouse-audit", "cluster_id": cid, "cluster_name": name,
            "state": "RUNNING" if running else "TERMINATED", "cluster_source": source,
            "autotermination_minutes": autoterm, "num_workers": workers, "autoscale_min": None,
            "autoscale_max": None, "node_type_id": node, "driver_node_type_id": node, "driver_cores": cores,
            "start_time": ms(start or t - timedelta(days=20)), "last_restarted_time": ms(start) if start else None,
            "last_activity_time": ms(activity) if activity else None,
        }

    # Interactive cluster with auto-termination off: often left running overnight after an afternoon session.
    adhoc_up = last or rng.random() < 0.6
    start = t - timedelta(hours=15 if last else rng.uniform(11, 16))
    activity = start + timedelta(hours=1 if last else rng.uniform(0.5, 2.5))
    # Single-node dev box on a 16-vCPU driver, sometimes started before office hours.
    ml_up = rng.random() < 0.4
    ml_start = t - timedelta(hours=rng.uniform(1.2, 3))
    return [
        cluster("1015-031200-adhoc01", "adhoc-analytics", "UI", 0, 2, "n2-highmem-16", 16, adhoc_up,
                start if adhoc_up else None, activity if adhoc_up else None),
        cluster("1002-101500-mldev02", "ml-dev-single-node", "UI", 120, 0, "n2-standard-16", 16, ml_up,
                ml_start if ml_up else None, t - timedelta(minutes=10) if ml_up else None),
        cluster("1020-190000-etl0003", "job-etl-nightly", "JOB", 0, 4, "n2-standard-4", 4, False),
        cluster("0930-020000-bisrv04", "bi-serving", "UI", 30, 1, "n2-standard-4", 4, True,
                t - timedelta(minutes=30), t - timedelta(minutes=5)),
    ]


def dataproc_clusters(i: int, created: datetime | None) -> list[dict]:
    # A Spark cluster someone created without an idle-delete TTL; deleted after a week of runs.
    if created is None or not 4 <= i <= 10:
        return []
    return [{
        "platform": "dataproc", "project": "moukda-lakehouse", "region": "asia-southeast1",
        "cluster_id": "5b1f0c2e-demo-4c1a-9d1e-spark0adhoc", "cluster_name": "spark-adhoc-sg", "state": "RUNNING",
        "state_start_time": iso(created), "num_workers": 2, "master_machine_type": "n2-standard-4",
        "worker_machine_type": "n2-standard-4", "idle_delete_ttl": None,
    }]


# ------------------------------------------------------------- storage (Module B)


def commit(version, ts, op, removed_bytes=0, removed_files=0, added_files=0):
    metrics = {"numAddedFiles": str(added_files)}
    if removed_bytes or removed_files:
        metrics |= {"numRemovedBytes": str(int(removed_bytes)), "numRemovedFiles": str(removed_files)}
    return {"version": version, "timestamp": iso(ts), "operation": op, "operationMetrics": json.dumps(metrics)}


def orders_history() -> list[dict]:
    """silver.orders: a nightly MERGE rewrites ~1 GB; VACUUM runs only now and then."""
    rng, out, v = random.Random(11), [], 0
    day = datetime(2026, 9, 1, 2, 0, tzinfo=timezone.utc)
    vacuums = {datetime(2026, 9, 20).date(), datetime(2026, 10, 8).date()}
    while day < datetime(2026, 11, 1, tzinfo=timezone.utc):
        out.append(commit(v, day, "MERGE", rng.uniform(0.6, 1.4) * GB, rng.randint(20, 45), rng.randint(20, 45)))
        v += 1
        if day.date() in vacuums:
            out.append(commit(v, day + timedelta(hours=1), "VACUUM END"))
            v += 1
        day += timedelta(days=1)
    return out


ORDERS_HISTORY = orders_history()


def tables(i: int, t: datetime, optimize_at: datetime) -> list[dict]:
    def table(name, files, size, history, retention="interval 7 days"):
        return {
            "table": name,
            "detail": {"numFiles": files, "sizeInBytes": int(size),
                       "properties": {"delta.deletedFileRetentionDuration": retention},
                       "partitionColumns": [], "clusteringColumns": []},
            "history": [h for h in history if h["timestamp"] <= iso(t)][-500:],
        }

    # bronze.events_raw: streaming appends pile up small files until an OPTIMIZE on the 9th run,
    # whose removed files then wait for a VACUUM.
    events_size = 12 * GB + 0.4 * GB * i
    events_files = 1400 + 160 * i if i < 8 else 260 + 150 * (i - 8)
    events_hist = [commit(n, optimize_at - timedelta(days=30 - n), "STREAMING UPDATE", added_files=160)
                   for n in range(30)]
    events_hist.append(commit(30, optimize_at, "OPTIMIZE", 14.8 * GB, 2520, 240))
    # bronze.clickstream: tiny files that cross the 2,000-file alert line late in the month.
    clicks_files = 900 + 90 * i
    return [
        table("lakehouse.bronze.events_raw", events_files, events_size, events_hist),
        table("lakehouse.bronze.clickstream", clicks_files, clicks_files * 0.9 * MB, []),
        table("lakehouse.silver.orders", 180, 45 * GB, ORDERS_HISTORY),
        table("lakehouse.gold.daily_kpis", 40, 3 * GB, [commit(0, t - timedelta(days=40), "WRITE", added_files=40)]),
    ]


# ------------------------------------------------------------- pipeline


def write_inputs(run_dir: Path, i: int, last: bool, t: datetime, times: list[datetime], rng: random.Random) -> None:
    run_dir.mkdir(parents=True, exist_ok=True)
    created = times[4] - timedelta(hours=3) if len(times) > 4 else None
    files = {
        "compute_databricks_lakehouse-audit.json": databricks_clusters(i, last, t, rng),
        "compute_dataproc_asia-southeast1.json": dataproc_clusters(i, created),
        "compute_dataproc_asia-southeast3.json": [],
        "storage_lakehouse-audit.json": tables(i, t, times[min(8, len(times) - 1)]),
    }
    for name, records in files.items():
        (run_dir / name).write_text(json.dumps(records, indent=2))


def feed(conn, cfg: Config, run_dir: Path, now: datetime, duration: float) -> report.ReportInput:
    """`finops run` (finops/__main__.py cmd_run) with an explicit clock."""
    compute_records, storage_records, notes, _ = load_run_dir(run_dir)
    compute_flags = [f for r in compute_records if (f := rules.evaluate_compute(r, now, cfg))]
    storage_flags = [f for r in storage_records if (f := rules.evaluate_storage(r, now, cfg))]
    waste = sum(f.est_daily_waste_usd for f in compute_flags)
    run_id = db.unique_run_id(conn, run_dir.name)
    trend = trends.compute(conn, cfg, run_id, waste, now)
    db.save_run(
        conn,
        RunRecord(
            run_id=run_id,
            timestamp_utc=now.strftime(trends.TS_FORMAT),
            target_environment=cfg.environment_name,
            total_compute_flagged=len(compute_flags),
            total_storage_flagged_gb=round(sum(f.size_gb for f in storage_flags), 3),
            estimated_daily_waste_usd=round(waste, 2),
            execution_duration_sec=duration,
        ),
        compute_flags,
        storage_flags,
    )
    now_local = now.astimezone(cfg.tz)
    return report.ReportInput(
        environment=cfg.environment_name, host="demo", run_id=run_id,
        run_time_local=f"{now_local:%a %d %b %H:%M} {cfg.timezone.split('/')[-1]} time",
        clusters_checked=len(compute_records), tables_checked=len(storage_records),
        compute=compute_flags, storage=storage_flags, trend=trend, notes=notes,
    )


def build(out: Path, now: datetime) -> report.ReportInput:
    """Rebuild OUT/demo.toml, OUT/runs/ and OUT/demo.db; returns the latest run's report input."""
    out.mkdir(parents=True, exist_ok=True)
    cfg = write_config(out)
    db_path = out / "demo.db"
    db_path.unlink(missing_ok=True)
    times = run_times(cfg, now)
    rng = random.Random(42)
    conn = db.connect(db_path)
    try:
        for i, t in enumerate(times):
            run_dir = out / "runs" / f"run_{t.astimezone(cfg.tz):%Y%m%d_%H%M}_demo"
            write_inputs(run_dir, i, i == len(times) - 1, t, times, rng)
            latest = feed(conn, cfg, run_dir, t, round(rng.uniform(28, 55), 1))
        for row in conn.execute(
            "SELECT run_id, total_compute_flagged, total_storage_flagged_gb, estimated_daily_waste_usd"
            " FROM audit_runs ORDER BY timestamp"
        ):
            print(*row, sep="\t")
    finally:
        conn.close()
    return latest


def main(argv: list[str]) -> int:
    out = Path(argv[0]) if argv else Path(__file__).resolve().parent / "out"
    latest = build(out, datetime.now(timezone.utc))
    print("\n--- latest demo report ---\n" + report.render(latest))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
